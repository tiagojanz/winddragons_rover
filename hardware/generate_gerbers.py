def draw_text_gerber(writer, text, start_x, start_y, char_height=1.5, d_code=None):
    scale = char_height / 7.0
    char_spacing = 5.2 * scale
    cur_x = start_x
    for ch in text.upper():
        strokes = FONT_5X7.get(ch, [])
        for x1, y1, x2, y2 in strokes:
            px1 = cur_x + x1 * scale
            py1 = start_y + y1 * scale
            px2 = cur_x + x2 * scale
            py2 = start_y + y2 * scale
            writer.draw_line(px1, py1, px2, py2, d_code)
        cur_x += char_spacing

class BoardBuilder:
    def __init__(self, name, width, height, output_dir):
        self.name = name
        self.w = width
        self.h = height
        self.out_dir = output_dir
        os.makedirs(output_dir, exist_ok=True)
        
        self.pads = []         # (x, y, drill, pad_w, pad_h, is_rect, net)
        self.tracks_top = []   # (x1, y1, x2, y2, width, net)
        self.tracks_bot = []   # (x1, y1, x2, y2, width, net)
        self.silk_lines = []   # (x1, y1, x2, y2, width)
        self.silk_texts = []   # (text, x, y, height)
        self.silk_rects = []   # (x1, y1, x2, y2, width)
        self.mounting_holes = [] # (x, y, drill, pad_dia)

    def add_mounting_hole(self, x, y, drill=3.2, pad_dia=6.0):
        self.mounting_holes.append((x, y, drill, pad_dia))

    def add_pin(self, x, y, drill=1.0, pad_size=1.7, is_pin1=False, net=""):
        self.pads.append((x, y, drill, pad_size, pad_size, is_pin1, net))

    def add_smd_pad(self, x, y, width, height, net=""):
        # drill = 0.0 indicates SMD pad!
        self.pads.append((x, y, 0.0, width, height, True, net))

    def add_smd_button(self, cx, cy, label="", net_sig=""):
        # Standard 6x6mm 4-pin SMD tactile switch
        # Left pads (1 & 2): Signal
        p1 = (cx - 3.25, cy + 2.25)
        p2 = (cx - 3.25, cy - 2.25)
        # Right pads (3 & 4): GND
        p3 = (cx + 3.25, cy + 2.25)
        p4 = (cx + 3.25, cy - 2.25)
        
        self.add_smd_pad(p1[0], p1[1], 1.8, 1.2, net=net_sig)
        self.add_smd_pad(p2[0], p2[1], 1.8, 1.2, net=net_sig)
        self.add_smd_pad(p3[0], p3[1], 1.8, 1.2, net="GND")
        self.add_smd_pad(p4[0], p4[1], 1.8, 1.2, net="GND")
        
        # Connect left pads together
        self.add_track_top(p1[0], p1[1], p2[0], p2[1], width=0.5, net=net_sig)
        # Connect right pads together
        self.add_track_top(p3[0], p3[1], p4[0], p4[1], width=0.5, net="GND")
        # Silkscreen box (6.2 x 6.2 mm)
        self.silk_rects.append((cx - 3.1, cy - 3.1, cx + 3.1, cy + 3.1, 0.15))
        # Silkscreen circle for plunger
        self.silk_rects.append((cx - 1.5, cy - 1.5, cx + 1.5, cy + 1.5, 0.12))
        if label:
            self.silk_texts.append((label, cx - 2.8, cy + 3.8, 0.8))
        return (cx, cy)

    def add_ps4_joystick(self, cx, cy, label="PS4 3D JOYSTICK", net_x="IO0_ADC", net_y="IO1_ADC"):
        # Alps RKJXV series (standard PS3/PS4/PS5/Xbox 3D analog thumbstick)
        # 1. 4 Corner frame mounting tabs (Chassis GND)
        tab_drill = 1.5
        tab_pad = 2.25
        self.add_pin(cx - 6.325, cy + 5.0, drill=tab_drill, pad_size=tab_pad, net="GND")
        self.add_pin(cx + 6.325, cy + 5.0, drill=tab_drill, pad_size=tab_pad, net="GND")
        self.add_pin(cx - 6.325, cy - 5.0, drill=tab_drill, pad_size=tab_pad, net="GND")
        self.add_pin(cx + 6.325, cy - 5.0, drill=tab_drill, pad_size=tab_pad, net="GND")

        # 2. 2 Side alignment/mounting tabs (Chassis GND)
        self.add_pin(cx - 4.3, cy, drill=1.6, pad_size=2.35, net="GND")
        self.add_pin(cx + 4.3, cy, drill=1.6, pad_size=2.35, net="GND")

        # 3. Potentiometer X (South: Y = cy - 8.73)
        pot_drill = 1.0
        pot_pad = 1.7
        self.add_pin(cx - 2.5, cy - 8.73, drill=pot_drill, pad_size=pot_pad, net="GND")
        self.add_pin(cx, cy - 8.73, drill=pot_drill, pad_size=pot_pad, is_pin1=True, net=net_x)
        self.add_pin(cx + 2.5, cy - 8.73, drill=pot_drill, pad_size=pot_pad, net="3V3")

        # 4. Potentiometer Y (East: X = cx + 8.73)
        self.add_pin(cx + 8.73, cy + 2.5, drill=pot_drill, pad_size=pot_pad, net="3V3")
        self.add_pin(cx + 8.73, cy, drill=pot_drill, pad_size=pot_pad, is_pin1=True, net=net_y)
        self.add_pin(cx + 8.73, cy - 2.5, drill=pot_drill, pad_size=pot_pad, net="GND")

        # 5. Push Switch (North: Y = cy + 5.75 and cy + 10.25)
        sw_drill = 1.2
        sw_pad = 1.8
        self.add_pin(cx - 3.25, cy + 5.75, drill=sw_drill, pad_size=sw_pad, net="GND")
        self.add_pin(cx + 3.25, cy + 5.75, drill=sw_drill, pad_size=sw_pad, net="SW")
        self.add_pin(cx - 3.25, cy + 10.25, drill=sw_drill, pad_size=sw_pad, net="GND")
        self.add_pin(cx + 3.25, cy + 10.25, drill=sw_drill, pad_size=sw_pad, net="SW")

        # 6. Silkscreen drawings
        self.silk_rects.append((cx - 6.6, cy - 6.6, cx + 6.6, cy + 6.6, 0.18))
        self.silk_rects.append((cx - 4.5, cy - 9.5, cx + 4.5, cy - 6.6, 0.15))
        self.silk_rects.append((cx + 6.6, cy - 4.5, cx + 9.5, cy + 4.5, 0.15))
        self.silk_rects.append((cx - 4.5, cy + 6.6, cx + 4.5, cy + 11.5, 0.15))
        for ang in range(0, 360, 30):
            rad1 = math.radians(ang)
            rad2 = math.radians(ang + 30)
            self.silk_lines.append((cx + 4.5 * math.cos(rad1), cy + 4.5 * math.sin(rad1),
                                    cx + 4.5 * math.cos(rad2), cy + 4.5 * math.sin(rad2), 0.15))
        if label:
            self.silk_texts.append((label, cx - 7.5, cy + 12.5, 0.85))
            self.silk_texts.append(("VRX", cx - 1.2, cy - 10.8, 0.7))
            self.silk_texts.append(("VRY", cx + 7.5, cy + 3.5, 0.7))
        return (cx, cy)

    def add_pin_header(self, x_start, y_start, pin_count, pitch=2.54, vertical=True, is_pin1_idx=1, net_list=None, label="", label_pos=(-2.0, 0)):
        if net_list is None:
            net_list = ["" for _ in range(pin_count)]
        pins = []
        for i in range(pin_count):
            if vertical:
                px = x_start
                py = y_start + i * pitch
            else:
                px = x_start + i * pitch
                py = y_start
            is_p1 = (i + 1 == is_pin1_idx)
            net = net_list[i] if i < len(net_list) else ""
            self.add_pin(px, py, drill=1.0, pad_size=1.7, is_pin1=is_p1, net=net)
            pins.append((px, py))
        
        margin = 1.4
        if vertical:
            rx1 = x_start - margin
            rx2 = x_start + margin
            ry1 = y_start - margin
            ry2 = y_start + (pin_count - 1) * pitch + margin
        else:
            rx1 = x_start - margin
            rx2 = x_start + (pin_count - 1) * pitch + margin
            ry1 = y_start - margin
            ry2 = y_start + margin
        self.silk_rects.append((rx1, ry1, rx2, ry2, 0.15))
        if label:
            lx = x_start + label_pos[0]
            ly = y_start + label_pos[1]
            self.silk_texts.append((label, lx, ly, 1.2))
        return pins

    def add_track_top(self, x1, y1, x2, y2, width=0.4, net=""):
        self.tracks_top.append((x1, y1, x2, y2, width, net))

    def add_track_bot(self, x1, y1, x2, y2, width=0.5, net=""):
        self.tracks_bot.append((x1, y1, x2, y2, width, net))

    def add_route_top(self, points, width=0.4, net=""):
        for i in range(len(points) - 1):
            self.add_track_top(points[i][0], points[i][1], points[i+1][0], points[i+1][1], width, net)

    def add_route_bot(self, points, width=0.5, net=""):
        for i in range(len(points) - 1):
            self.add_track_bot(points[i][0], points[i][1], points[i+1][0], points[i+1][1], width, net)

    def generate_all(self):
        prefix = self.name
        
        # 1. Edge Cuts
        gko = GerberWriter(os.path.join(self.out_dir, f"{prefix}-Edge_Cuts.gko"), "Board Outline")
        d_outline = gko.define_circle_aperture(0.15)
        w, h = self.w, self.h
        r = 2.0
        gko.draw_polyline([
            (r, 0), (w - r, 0), (w, r), (w, h - r), (w - r, h),
            (r, h), (0, h - r), (0, r), (r, 0)
        ], d_outline)
        gko.write()

        # 2. Drill file (Excellon)
        drl = ExcellonWriter(os.path.join(self.out_dir, f"{prefix}.drl"))
        for mh in self.mounting_holes:
            drl.add_hole(mh[0], mh[1], mh[2])
        for p in self.pads:
            if p[2] > 0: # only THT pads have drill holes!
                drl.add_hole(p[0], p[1], p[2])
        drl.write()

        # 3. Top Copper (F_Cu.gtl)
        gtl = GerberWriter(os.path.join(self.out_dir, f"{prefix}-F_Cu.gtl"), "Top Copper")
        d_mh = gtl.define_circle_aperture(6.0)
        for mh in self.mounting_holes:
            gtl.flash_pad(mh[0], mh[1], d_mh)
        
        d_pad_circ = gtl.define_circle_aperture(1.7)
        rect_aps = {}
        for p in self.pads:
            if p[5] or p[3] != p[4]:
                dim = (round(p[3], 2), round(p[4], 2))
                if dim not in rect_aps:
                    rect_aps[dim] = gtl.define_rect_aperture(dim[0], dim[1])
                gtl.flash_pad(p[0], p[1], rect_aps[dim])
            else:
                gtl.flash_pad(p[0], p[1], d_pad_circ)
        
        track_aps = {}
        for tr in self.tracks_top:
            w_key = round(tr[4], 3)
            if w_key not in track_aps:
                track_aps[w_key] = gtl.define_circle_aperture(w_key)
            gtl.draw_line(tr[0], tr[1], tr[2], tr[3], track_aps[w_key])
        gtl.write()

        # 4. Bottom Copper (B_Cu.gbl)
        gbl = GerberWriter(os.path.join(self.out_dir, f"{prefix}-B_Cu.gbl"), "Bottom Copper")
        d_mh_bot = gbl.define_circle_aperture(6.0)
        for mh in self.mounting_holes:
            gbl.flash_pad(mh[0], mh[1], d_mh_bot)
        
        d_pad_circ_b = gbl.define_circle_aperture(1.7)
        d_pad_rect_b = gbl.define_rect_aperture(1.7, 1.7)
        for p in self.pads:
            if p[2] > 0: # Only THT pads on bottom copper
                if p[5]:
                    gbl.flash_pad(p[0], p[1], d_pad_rect_b)
                else:
                    gbl.flash_pad(p[0], p[1], d_pad_circ_b)
        
        track_aps_b = {}
        for tr in self.tracks_bot:
            w_key = round(tr[4], 3)
            if w_key not in track_aps_b:
                track_aps_b[w_key] = gbl.define_circle_aperture(w_key)
            gbl.draw_line(tr[0], tr[1], tr[2], tr[3], track_aps_b[w_key])
        gbl.write()

        # 5. Top Solder Mask (F_Mask.gts)
        gts = GerberWriter(os.path.join(self.out_dir, f"{prefix}-F_Mask.gts"), "Top Solder Mask")
        d_mh_mask = gts.define_circle_aperture(6.2)
        for mh in self.mounting_holes:
            gts.flash_pad(mh[0], mh[1], d_mh_mask)
        d_mask_circ = gts.define_circle_aperture(1.9)
        mask_rect_aps = {}
        for p in self.pads:
            if p[5] or p[3] != p[4]:
                dim = (round(p[3] + 0.2, 2), round(p[4] + 0.2, 2))
                if dim not in mask_rect_aps:
                    mask_rect_aps[dim] = gts.define_rect_aperture(dim[0], dim[1])
                gts.flash_pad(p[0], p[1], mask_rect_aps[dim])
            else:
                gts.flash_pad(p[0], p[1], d_mask_circ)
        gts.write()

        # 6. Bottom Solder Mask (B_Mask.gbs)
        gbs = GerberWriter(os.path.join(self.out_dir, f"{prefix}-B_Mask.gbs"), "Bottom Solder Mask")
        d_mh_mask_b = gbs.define_circle_aperture(6.2)
        d_mask_circ_b = gbs.define_circle_aperture(1.9)
        d_mask_rect_b = gbs.define_rect_aperture(1.9, 1.9)
        for mh in self.mounting_holes:
            gbs.flash_pad(mh[0], mh[1], d_mh_mask_b)
        for p in self.pads:
            if p[2] > 0: # Only THT pads on bottom mask
                if p[5]:
                    gbs.flash_pad(p[0], p[1], d_mask_rect_b)
                else:
                    gbs.flash_pad(p[0], p[1], d_mask_circ_b)
        gbs.write()

        # 7. Top Silkscreen (F_Silkscreen.gto)
        gto = GerberWriter(os.path.join(self.out_dir, f"{prefix}-F_Silkscreen.gto"), "Top Silkscreen")
        d_silk_thin = gto.define_circle_aperture(0.15)
        gto.draw_rect_outline(1.5, 1.5, w - 1.5, h - 1.5, d_silk_thin)
        for rx1, ry1, rx2, ry2, sw in self.silk_rects:
            gto.draw_rect_outline(rx1, ry1, rx2, ry2, d_silk_thin)
        for x1, y1, x2, y2, sw in self.silk_lines:
            gto.draw_line(x1, y1, x2, y2, d_silk_thin)
        for txt, tx, ty, th in self.silk_texts:
            draw_text_gerber(gto, txt, tx, ty, char_height=th, d_code=d_silk_thin)
        gto.write()

        # 8. Bottom Silkscreen (B_Silkscreen.gbo)
        gbo = GerberWriter(os.path.join(self.out_dir, f"{prefix}-B_Silkscreen.gbo"), "Bottom Silkscreen")
        d_silk_b = gbo.define_circle_aperture(0.15)
        draw_text_gerber(gbo, f"WINDDRAGONS {prefix.upper()} V3.0", 8, 8, char_height=2.0, d_code=d_silk_b)
        draw_text_gerber(gbo, "100% PLANAR ZERO-CROSSING ROUTING", 8, 5, char_height=1.2, d_code=d_silk_b)
        gbo.write()

        # 9. ZIP package
        zip_path = os.path.join(self.out_dir, f"Gerber_{prefix}.zip")
        with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
            for ext in ["-F_Cu.gtl", "-B_Cu.gbl", "-F_Mask.gts", "-B_Mask.gbs", "-F_Silkscreen.gto", "-B_Silkscreen.gbo", "-Edge_Cuts.gko", ".drl"]:
                fname = f"{prefix}{ext}"
                fpath = os.path.join(self.out_dir, fname)
                if os.path.exists(fpath):
                    zf.write(fpath, arcname=fname)
        print(f"Created ZIP: {zip_path}")

        self.render_svg_and_png()
        self.generate_kicad_pcb()

