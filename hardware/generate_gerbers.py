SCALE = 10000

def to_gerber_coord(x, y):
    ix = int(round(x * SCALE))
    iy = int(round(y * SCALE))
    return f"X{ix}Y{iy}"

def to_excellon_coord(x, y):
    ix = int(round(x * 1000))
    iy = int(round(y * 1000))
    return f"X{ix}Y{iy}"

class GerberWriter:
    def __init__(self, filename, layer_name=""):
        self.filename = filename
        self.layer_name = layer_name
        self.lines = [
            "%FSLAX44Y44*%",
            "%MOMM*%",
            "%LPD*%",
            f"G04 Layer: {layer_name}*%",
            "G04 Generated by WindDragons EDA Generator (100% Planar Zero-Crossing)*%",
        ]
        self.apertures = {}
        self.next_d = 10
        self.current_d = None
        self.body_lines = []

    def define_circle_aperture(self, diameter):
        key = ("C", round(diameter, 4))
        if key not in self.apertures:
            d_code = self.next_d
            self.next_d += 1
            self.apertures[key] = d_code
            self.lines.append(f"%ADD{d_code}C,{diameter:.4f}*%")
        return self.apertures[key]

    def define_rect_aperture(self, width, height):
        key = ("R", round(width, 4), round(height, 4))
        if key not in self.apertures:
            d_code = self.next_d
            self.next_d += 1
            self.apertures[key] = d_code
            self.lines.append(f"%ADD{d_code}R,{width:.4f}X{height:.4f}*%")
        return self.apertures[key]

    def set_aperture(self, d_code):
        if self.current_d != d_code:
            self.body_lines.append(f"D{d_code}*")
            self.current_d = d_code

    def flash_pad(self, x, y, d_code):
        self.set_aperture(d_code)
        self.body_lines.append(f"{to_gerber_coord(x, y)}D03*")

    def draw_line(self, x1, y1, x2, y2, d_code):
        self.set_aperture(d_code)
        self.body_lines.append(f"{to_gerber_coord(x1, y1)}D02*")
        self.body_lines.append(f"{to_gerber_coord(x2, y2)}D01*")

    def draw_polyline(self, points, d_code):
        if not points:
            return
        self.set_aperture(d_code)
        self.body_lines.append(f"{to_gerber_coord(points[0][0], points[0][1])}D02*")
        for pt in points[1:]:
            self.body_lines.append(f"{to_gerber_coord(pt[0], pt[1])}D01*")

    def draw_rect_outline(self, x1, y1, x2, y2, d_code):
        pts = [(x1, y1), (x2, y1), (x2, y2), (x1, y2), (x1, y1)]
        self.draw_polyline(pts, d_code)

    def write(self):
        with open(self.filename, "w") as f:
            for l in self.lines:
                f.write(l + "\n")
            for l in self.body_lines:
                f.write(l + "\n")
            f.write("M02*\n")

class ExcellonWriter:
    def __init__(self, filename):
        self.filename = filename
        self.tools = {}
        self.hits = {}
        self.next_tool = 1

    def add_hole(self, x, y, diameter):
        dia_key = round(diameter, 3)
        if dia_key not in self.tools:
            t_id = self.next_tool
            self.next_tool += 1
            self.tools[dia_key] = t_id
            self.hits[t_id] = []
        t_id = self.tools[dia_key]
        self.hits[t_id].append((x, y))

    def write(self):
        with open(self.filename, "w") as f:
            f.write("M48\n")
            f.write("; DRILL file for WindDragons PCB\n")
            f.write("METRIC,TZ\n")
            f.write("FMAT,2\n")
            for dia, t_id in sorted(self.tools.items()):
                f.write(f"T{t_id}C{dia:.3f}\n")
            f.write("%\n")
            f.write("G90\n")
            f.write("G05\n")
            for dia, t_id in sorted(self.tools.items()):
                f.write(f"T{t_id}\n")
                for x, y in self.hits[t_id]:
                    f.write(f"{to_excellon_coord(x, y)}\n")
            f.write("M30\n")

